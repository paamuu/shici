@Injectable({ providedIn: 'root' })
export class PoemsService {
  readonly poems = poemsData;

  getAuthors(): string[] {
    return [...new Set(this.poems.map((p) => p.author))];
  }

  getCipais(): string[] {
    return [...new Set(this.poems.map((p) => p.cipai))];
  }

  getDynasties(): string[] {
    return [...new Set(this.poems.map((p) => p.dynasty))];
  }

  getThemes(): string[] {
    return [...new Set(this.poems.flatMap((p) => p.theme))];
  }

  getPoemById(id: string): Poem | undefined {
    return this.poems.find((p) => p.id === id);
  }
}
